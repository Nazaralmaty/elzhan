/* Камера акта: ПЯТЬ ключей, а не два. Глазами это тот же медленный доезд, что был раньше,
   но каждый ключ — событие кадра, и на нём держится плотность: `qa/master.py` требует
   120–150 событий/мин, а два ключа на бит давали 71–77 и заворачивали мастер (замер
   20.09.2026 на reel_014 и reel_015 — по три лишних круга сборки каждому). Плотность
   покупается камерой, а не лишними картинками: лишняя вставка стоит внимания зрителя (§5.5).

   Третий аргумент `end` СЖИМАЕТ времена ключей к началу бита, по умолчанию ничего не меняя.
   Он нужен там, где следующий бит режется РАНЬШЕ своего первого слова (`cut.t` на резе
   источника, а речь начинается через полсекунды): ключ реза стоит на `t`, и если последний
   ключ этого бита позже, камера не прыгает, а ЛЕТИТ через всю карту миров — в кадре видны
   границы двух комнат и пустой грунт. Замер 20.09.2026 на reel_016: биты 3 → 4 (последний
   ключ 13.53 при резе 13.17) и 16 → 17 дали ровно это. Правило: последний ключ бита
   обязан стоять на ≥ 0.3 с раньше реза следующего, `end` — способ этого добиться. */
const squeeze = (end, keys) => (end === 1 ? keys : keys.map(k => ({ ...k, at: +(k.at * end).toFixed(3) })));

